export function localizedError(message: string, locale: Locale): string {
  if (locale === "en" || !message) return message;
  const text = message.trim();
  if (Object.hasOwn(messages, text)) return messages[text];
  const range = /^(.+) must be (-?[\d.]+) to (-?[\d.]+)\.$/.exec(text);
  if (range && Object.hasOwn(toneLabels, range[1])) return `${toneLabels[range[1]]}须在 ${range[2]} 至 ${range[3]} 之间。`;
  for (const [pattern, translation] of patterns) {
    if (pattern.test(text)) return text.replace(pattern, translation);
  }
  if (/\p{Script=Han}/u.test(text)) return text;
  if (/out of memory/i.test(text)) return `内存或显存不足。原始错误：${text}`;
  return `错误详情：${text}`;
}
